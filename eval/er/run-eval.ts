import { mkdirSync, writeFileSync } from "node:fs";
import path from "node:path";
import {
  MATCH_THRESHOLD,
  REVIEW_THRESHOLD,
  scoreErFeatures,
  type ErScore,
} from "../../src/domain/er";
import { loadErWeights } from "../../src/domain/er-weights";
import { computePairFeatures, loadLabeledPairs, type PairWithFeatures } from "./shared";

const PRECISION_TARGET = 0.95;
const RECALL_TARGET = 0.85;

interface Scored extends PairWithFeatures {
  result: ErScore;
}

interface BandStats {
  threshold: number;
  tp: number;
  fp: number;
  fn: number;
  tn: number;
  precision: number;
  recall: number;
  f1: number;
}

function bandStats(scored: Scored[], threshold: number): BandStats {
  let tp = 0;
  let fp = 0;
  let fn = 0;
  let tn = 0;
  for (const item of scored) {
    const predicted = item.result.score >= threshold;
    const actual = item.label === "match";
    if (predicted && actual) tp++;
    else if (predicted && !actual) fp++;
    else if (!predicted && actual) fn++;
    else tn++;
  }
  const precision = tp + fp === 0 ? 1 : tp / (tp + fp);
  const recall = tp + fn === 0 ? 1 : tp / (tp + fn);
  const f1 = precision + recall === 0 ? 0 : (2 * precision * recall) / (precision + recall);
  return { threshold, tp, fp, fn, tn, precision, recall, f1 };
}

const pct = (value: number) => `${(value * 100).toFixed(1)}%`;
const fixed = (value: number) => value.toFixed(3);

function pairLabel(item: Scored): string {
  return `${item.a.name} <${item.a.email}> ↔ ${item.b.name} <${item.b.email}>`;
}

function featureSummary(item: Scored): string {
  const f = item.features;
  const caps = item.result.caps.length ? ` caps=${item.result.caps.join("+")}` : "";
  return `vec ${fixed(f.vecCos)}, JW ${fixed(f.nameJW)}, sort ${fixed(f.nameTokenSort)}, email ${fixed(f.emailLocalSim)}, dest ${f.sameDestination}, country ${f.sameCountry ?? "?"}${caps}`;
}

function statsRow(name: string, s: BandStats): string {
  return `| ${name} | ${s.threshold} | ${s.tp} | ${s.fp} | ${s.fn} | ${s.tn} | ${pct(s.precision)} | ${pct(s.recall)} | ${fixed(s.f1)} |`;
}

function buildReport(scored: Scored[], match: BandStats, review: BandStats): string {
  const weights = loadErWeights();
  const positives = scored.filter((s) => s.label === "match");
  const negatives = scored.filter((s) => s.label === "nonmatch");

  const precisionOk = match.precision >= PRECISION_TARGET;
  const recallOk = review.recall >= RECALL_TARGET;

  const categories = [...new Set(positives.map((p) => p.category))];
  const categoryRows = categories.map((category) => {
    const group = positives.filter((p) => p.category === category);
    const matched = group.filter((p) => p.result.score >= MATCH_THRESHOLD).length;
    const reviewed = group.filter((p) => p.result.score >= REVIEW_THRESHOLD).length;
    return `| ${category} | ${group.length} | ${matched} | ${reviewed} | ${pct(reviewed / group.length)} |`;
  });

  const falsePositivesAtMatch = negatives.filter((n) => n.result.score >= MATCH_THRESHOLD);
  const falsePositivesAtReview = negatives.filter(
    (n) => n.result.score >= REVIEW_THRESHOLD && n.result.score < MATCH_THRESHOLD,
  );
  const missedAtReview = positives.filter((p) => p.result.score < REVIEW_THRESHOLD);
  const reviewOnlyPositives = positives.filter(
    (p) => p.result.score >= REVIEW_THRESHOLD && p.result.score < MATCH_THRESHOLD,
  );
  const briefHard = negatives.filter((n) => n.category === "brief-hard");

  const list = (items: Scored[]) =>
    items.length === 0
      ? ["_none_"]
      : items.map(
          (item) =>
            `- \`${item.id}\` (${item.category}) **${fixed(item.result.score)}** — ${pairLabel(item)}  \n  ${featureSummary(item)}`,
        );

  return [
    "# Entity resolution evaluation",
    "",
    "_Generated by `pnpm er:eval` (`eval/er/run-eval.ts`). Do not edit by hand._",
    "",
    `- Weights: \`${weights.version}\` (\`src/domain/er-weights.v1.json\`)`,
    `- Labeled pairs: ${scored.length} (${positives.length} match, ${negatives.length} non-match) from \`eval/er/labeled-pairs.json\``,
    `- Embeddings: real \`Xenova/all-MiniLM-L6-v2\` (384 dims) on \`name | email-local | country\`; no Elasticsearch involved`,
    `- Bands: MATCH ≥ ${MATCH_THRESHOLD} (CRITICAL, blocking), REVIEW ≥ ${REVIEW_THRESHOLD} (WARN)`,
    "",
    "## Targets",
    "",
    "| Target | Goal | Result | Status |",
    "|---|---|---|---|",
    `| Precision at MATCH | ≥ ${pct(PRECISION_TARGET)} | ${pct(match.precision)} | ${precisionOk ? "✅ met" : "❌ NOT met"} |`,
    `| Recall at REVIEW | ≥ ${pct(RECALL_TARGET)} | ${pct(review.recall)} | ${recallOk ? "✅ met" : "❌ NOT met"} |`,
    "",
    "## Per band",
    "",
    "A pair counts as predicted-positive when its score is at or above the threshold.",
    "",
    "| Band | Threshold | TP | FP | FN | TN | Precision | Recall | F1 |",
    "|---|---|---|---|---|---|---|---|---|",
    statsRow("MATCH", match),
    statsRow("REVIEW (or above)", review),
    "",
    "## Positives by category",
    "",
    "| Category | Pairs | ≥ MATCH | ≥ REVIEW | Recall at REVIEW |",
    "|---|---|---|---|---|",
    ...categoryRows,
    "",
    "## BRIEF §9 hard negatives (must not be MATCH)",
    "",
    ...list(briefHard),
    "",
    "## Confusion list",
    "",
    `### False positives at MATCH (${falsePositivesAtMatch.length})`,
    "",
    ...list(falsePositivesAtMatch),
    "",
    `### Non-matches that land in the REVIEW band (${falsePositivesAtReview.length}) — a human looks, nothing blocks`,
    "",
    ...list(falsePositivesAtReview),
    "",
    `### Missed matches below REVIEW (${missedAtReview.length})`,
    "",
    ...list(missedAtReview),
    "",
    `### True matches that only reach REVIEW, not MATCH (${reviewOnlyPositives.length})`,
    "",
    ...list(reviewOnlyPositives),
    "",
    "## Notes and honest caveats",
    "",
    "- **The numbers above are in-sample.** The labeled set is synthetic, written by us, and the weights were fitted on it (`pnpm er:tune`: logistic regression, then a straight-line rescale so the fixed thresholds 0.65 / 0.85 land on the data). `er:tune` also prints a hold-out check (fit on every second pair, test on the rest); when last run it gave 100% precision at MATCH and ~94% recall at REVIEW on the held-out half (about 68 pairs, so treat it as a rough signal, not a guarantee).",
    "- Two pairs are anchored on purpose because BRIEF §9 needs them: the hero pair `John Doe ↔ Jon Doe` (S1) must reach MATCH and `Mohammed Al-Rashid ↔ Muhammad Alrashid` (S9) must stay in the REVIEW band. The tuner moves the cut points to honour that.",
    "- **Labeling rule worth knowing:** two *different* real people whose names are only one typo apart (e.g. Laura / Lara) cannot be told apart from a typo by any pairwise score, so the set only contains such negatives when the countries differ (`near-name-diff-country`). In the app a one-typo look-alike gets a REVIEW or MATCH flag and a human decides.",
    "- Pure pair scoring cannot tell two *real* people with the same name and country apart either. In the app that case is handled by the established-vs-established rule in `resolve.ts`: two established payees are not flagged unless they share a destination.",
    "- New payees have no country, so `sameCountry` is unknown for them. Only a known country mismatch counts (as a penalty); the fitted penalty is large because every country mismatch in the set is a true non-match, so it acts almost like a veto. Real-world data may deserve a softer value.",
    "- `emailLocalSim` fitted to weight 0 here: in this synthetic set both true and false pairs have similar-looking emails, so it does not separate them. It is still reported as evidence (`er.emailLocal`) and `sameDestination` (an exact email match) is used. Revisit with real data.",
    "- Features beyond the §11.5 list: `nameNearIdentical` (names are one typo apart or the same words reordered). Name JW is the better of whole-string Jaro-Winkler and a word-by-word average; token-sort also tries the version without spaces.",
    "",
  ].join("\n");
}

async function main() {
  const pairs = loadLabeledPairs();
  const withFeatures = await computePairFeatures(pairs);
  const scored: Scored[] = withFeatures.map((item) => ({
    ...item,
    result: scoreErFeatures(item.features),
  }));

  const match = bandStats(scored, MATCH_THRESHOLD);
  const review = bandStats(scored, REVIEW_THRESHOLD);

  console.log(`ER eval — weights ${loadErWeights().version}, ${scored.length} pairs`);
  console.log(
    `  precision@MATCH(${MATCH_THRESHOLD}) = ${pct(match.precision)}  (tp ${match.tp}, fp ${match.fp}, recall ${pct(match.recall)})`,
  );
  console.log(
    `  recall@REVIEW(${REVIEW_THRESHOLD})   = ${pct(review.recall)}  (tp ${review.tp}, fn ${review.fn}, precision ${pct(review.precision)})`,
  );

  const precisionOk = match.precision >= PRECISION_TARGET;
  const recallOk = review.recall >= RECALL_TARGET;
  console.log(`  targets: precision ${precisionOk ? "met" : "NOT met"}, recall ${recallOk ? "met" : "NOT met"}`);

  const out = path.join(process.cwd(), "docs", "ER_EVAL.md");
  mkdirSync(path.dirname(out), { recursive: true });
  writeFileSync(out, buildReport(scored, match, review), "utf8");
  console.log(`  wrote ${path.relative(process.cwd(), out)}`);
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
